export function AuthSilosEditor(props: EditorProps) {
  const content = (props.content ?? {}) as Item
  const policies: Item[] = Array.isArray(content.authenticationPolicies) ? content.authenticationPolicies : []
  const silos: Item[] = Array.isArray(content.authenticationPolicySilos) ? content.authenticationPolicySilos : []
  const sync: Item[] = Array.isArray(content.deviceGroupSync) ? content.deviceGroupSync : []
  const [tab, setTab] = React.useState<TabKey>('policies')
  const bind = (listKey: string) => (next: Item[], tag?: string) => props.setContent({ ...content, [listKey]: next }, tag)
  const enforced = [...policies, ...silos].filter((x) => x.enforce).length

  return (
    <div className="grid min-w-0 gap-4 [&>*]:min-w-0">
      <div className="flex gap-3 rounded-xl border bg-card px-4 py-3 text-[13px] text-muted-foreground">
        <ShieldCheck className="mt-0.5 size-4 shrink-0 text-sky-600 dark:text-sky-400" />
        <p className="min-w-0">
          {t('config.authsiloEditor.policiesDefineFromWhichDevices')}
          {enforced > 0 ? t('config.authsiloEditor.enforcedNow', { count: enforced }) : '.'}
        </p>
      </div>
      <Tabs value={tab} onValueChange={(v) => setTab(v as TabKey)}>
        <div className="max-w-full overflow-x-auto">
          <TabsList aria-label={t('config.authsiloEditor.areasOfTheAuthenticationSilos')}>
            <TabsTrigger value="policies" className="max-sm:[&>svg]:hidden"><KeyRound /> {t('config.authsiloEditor.policies')} <Badge variant="muted" className="ml-0.5">{policies.length}</Badge></TabsTrigger>
            <TabsTrigger value="silos" className="max-sm:[&>svg]:hidden"><Boxes /> {t('config.authsiloEditor.silos')} <Badge variant="muted" className="ml-0.5">{silos.length}</Badge></TabsTrigger>
            <TabsTrigger value="sync" className="max-sm:[&>svg]:hidden"><MonitorSmartphone /> <span><span className="hidden sm:inline">{t('config.authsiloEditor.deviceGroup2')}</span>{t('config.authsiloEditor.synchronization2')}</span> <Badge variant="muted" className="ml-0.5">{sync.length}</Badge></TabsTrigger>
          </TabsList>
        </div>
        <TabsContent value="policies">
          <PoliciesList items={policies} onItemsChange={bind('authenticationPolicies')} readOnly={props.readOnly} />
        </TabsContent>
        <TabsContent value="silos">
          <SilosList items={silos} onItemsChange={bind('authenticationPolicySilos')} readOnly={props.readOnly} policies={policies} />
        </TabsContent>
        <TabsContent value="sync">
          <SyncList items={sync} onItemsChange={bind('deviceGroupSync')} readOnly={props.readOnly} />
        </TabsContent>
      </Tabs>
    </div>
  )
}

