export function validatePolicy(p: Item, all: Item[], index: number | null): Record<string, string> {
  const e: Record<string, string> = {}
  const name = String(p.name ?? '').trim()
  if (!name) e.name = t('config.authsiloEditor.nameIsRequired')
  else if (all.some((x, i) => i !== index && String(x.name ?? '').trim().toLowerCase() === name.toLowerCase())) e.name = t('config.authsiloEditor.aPolicyWithThisName')
  const tgt = p.userTgtLifetimeMins
  if (tgt !== null && tgt !== undefined && (!Number.isInteger(tgt) || tgt < TGT_MIN || tgt > TGT_MAX))
    e.userTgtLifetimeMins = t('config.authsiloEditor.pleaseEnterAWholeNumber', { tGT_MIN: TGT_MIN, tGT_MAX: TGT_MAX })
  return e
}

