function SiloSentence({ silo, userPolicy }: { silo: Item; userPolicy: Item | undefined }) {
  const m = (silo.members ?? {}) as Item
  const who: string[] = []
  const userOus = strings(m.userOUs)
  const computerOus = strings(m.computerOUs)
  const groups = strings(m.computerGroups)
  if (userOus.length) who.push(t('config.authsiloEditor.allUsersUnderJoin', { join: userOus.map(lastRdn).join(', ') }))
  if (computerOus.length) who.push(t('config.authsiloEditor.allComputersUnderJoin', { join: computerOus.map(lastRdn).join(', ') }))
  if (groups.length) who.push(t('config.authsiloEditor.computersOfGroups', { count: groups.length, groups: groups.join(', ') }))
  const excluded = strings(m.excludeAccounts)
  return (
    <>
      {who.length ? (
        <p>
          {t('config.authsiloEditor.included', { who: who.join(', ') })}
          {excluded.length ? t('config.authsiloEditor.exceptJoin', { join: excluded.join(', ') }) : ''}.
        </p>
      ) : (
        <p className="text-muted-foreground">{t('config.authsiloEditor.noMembersDefinedYet')}</p>
      )}
      <p className="mt-1">
        {silo.userAuthenticationPolicy ? (
          <>{t('config.authsiloEditor.forTheirUserAccounts')} {policyRuleText(userPolicy)}{userPolicy ? '.' : t('config.authsiloEditor.policyIsNotConfigured')}</>
        ) : (
          <span className="text-muted-foreground">{t('config.authsiloEditor.withoutAUserPolicyThe')}</span>
        )}
      </p>
      <p className="mt-1 text-muted-foreground">{silo.enforce ? t('config.authsiloEditor.theSiloIsEnforced') : t('config.authsiloEditor.theSiloRunsInAudit')}</p>
    </>
  )
}

