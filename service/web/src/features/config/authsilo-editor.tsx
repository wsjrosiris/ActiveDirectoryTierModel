/** Sentence for a policy's sign-in rule. */
export function policyRuleText(p: Item | undefined): string {
  const from = (p?.allowedToAuthenticateFrom ?? {}) as Item
  return describeSignInRule(!!from.includeDomainControllers, strings(from.deviceGroups))
}

