export function validateSilo(s: Item, all: Item[], index: number | null, policies: Item[]): Record<string, string> {
  const e: Record<string, string> = {}
  const name = String(s.name ?? '').trim()
  if (!name) e.name = t('config.authsiloEditor.nameIsRequired')
  else if (all.some((x, i) => i !== index && String(x.name ?? '').trim().toLowerCase() === name.toLowerCase())) e.name = t('config.authsiloEditor.aSiloWithThisName')
  const known = new Set(policies.map((p) => String(p.name ?? '').toLowerCase()))
  for (const field of ['userAuthenticationPolicy', 'computerAuthenticationPolicy', 'serviceAuthenticationPolicy'])
    if (s[field] && !known.has(String(s[field]).toLowerCase())) e[field] = t('config.authsiloEditor.thisPolicyIsNotConfigured')
  return e
}

