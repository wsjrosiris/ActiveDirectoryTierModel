/** "OU=Tier 0 Accounts,OU=Tier 0,OU=Admin,{{DOMAIN_DN}}" → "Admin › Tier 0 › Tier 0 Accounts" */
export function ouLabel(dn: string): string {
  const rel = dn.replace(/,?\{\{DOMAIN_DN\}\}$/i, '')
  if (!rel) return t('config.authsiloEditor.domainRoot')
  return rel
    .split(/,(?=\s*[A-Za-z]+=)/)
    .map((p) => p.trim().replace(/^[A-Za-z]+=/, ''))
    .reverse()
    .join(' › ')
}

const lastRdn = (dn: string) => ouLabel(dn).split(' › ').pop() ?? dn

const strings = (v: unknown): string[] => (Array.isArray(v) ? v.filter((x): x is string => typeof x === 'string' && !!x) : [])

function itemTier(o: Item): Tier {
  const tt = authTier(o)
  return tt === 0 || tt === 1 || tt === 2 ? tt : tierOf(o.name ?? o.group)
}

function ModeBadge({ enforce }: { enforce: unknown }) {
  return enforce ? <Badge variant="danger">{t('config.authsiloEditor.enforced')}</Badge> : <Badge variant="info">{t('config.authsiloEditor.audit')}</Badge>
}

