function SiloSentence({ silo, userPolicy }: { silo: Item; userPolicy: Item | undefined }) {
  const m = (silo.members ?? {}) as Item
  const who: string[] = []
  const userOus = strings(m.userOUs)
  const computerOus = strings(m.computerOUs)
  const groups = strings(m.computerGroups)
  if (userOus.length) who.push(`alle Benutzer unter ${userOus.map(lastRdn).join(', ')}`)
  if (computerOus.length) who.push(`alle Computer unter ${computerOus.map(lastRdn).join(', ')}`)
  if (groups.length) who.push(`die Computer der Gruppe${groups.length > 1 ? 'n' : ''} ${groups.join(', ')}`)
  const excluded = strings(m.excludeAccounts)
  return (
    <>
      {who.length ? (
        <p>
          Aufgenommen werden {who.join(', ')}
          {excluded.length ? `, außer ${excluded.join(', ')}` : ''}.
        </p>
      ) : (
        <p className="text-muted-foreground">Noch keine Mitglieder festgelegt.</p>
      )}
      <p className="mt-1">
        {silo.userAuthenticationPolicy ? (
          <>Für ihre Benutzerkonten gilt: {policyRuleText(userPolicy)}{userPolicy ? '.' : ' (Richtlinie ist nicht konfiguriert).'}</>
        ) : (
          <span className="text-muted-foreground">Ohne Benutzerrichtlinie schränkt das Silo die Anmeldung nicht ein.</span>
        )}
      </p>
      <p className="mt-1 text-muted-foreground">{silo.enforce ? 'Das Silo wird erzwungen.' : 'Das Silo läuft im Überwachungsmodus.'}</p>
    </>
  )
}

