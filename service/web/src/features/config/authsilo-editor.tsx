export function validatePolicy(p: Item, all: Item[], index: number | null): Record<string, string> {
  const e: Record<string, string> = {}
  const name = String(p.name ?? '').trim()
  if (!name) e.name = 'Name ist erforderlich.'
  else if (all.some((x, i) => i !== index && String(x.name ?? '').trim().toLowerCase() === name.toLowerCase())) e.name = 'Eine Richtlinie mit diesem Namen existiert bereits.'
  const tgt = p.userTgtLifetimeMins
  if (tgt !== null && tgt !== undefined && (!Number.isInteger(tgt) || tgt < TGT_MIN || tgt > TGT_MAX))
    e.userTgtLifetimeMins = `Bitte eine ganze Zahl von ${TGT_MIN} bis ${TGT_MAX} angeben oder leer lassen.`
  return e
}

